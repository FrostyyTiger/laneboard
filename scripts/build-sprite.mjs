#!/usr/bin/env node
// Build the Lucide icon sprite from a pinned lucide-static checkout (fleet D2).
//
//   node scripts/build-sprite.mjs <lucide-static>/icons > public/vendor/lucide/sprite.svg
//   node scripts/build-sprite.mjs <lucide-static>/icons --license public/vendor/lucide/LICENSE
//
// lucide-static is NOT a dependency: fetch the version pinned in scripts/icons.json once
// (`npm pack lucide-static@<version>` in a temp dir, outside the repo), point this script
// at its icons/ directory and commit only the generated sprite and LICENSE.
//
// Each concept in scripts/icons.json becomes <symbol id="i-<concept>" viewBox="0 0 24 24">
// holding the Lucide SVG body. The per-file stroke*/fill attributes are dropped (the sprite
// is styled by the .i class). A missing Lucide name exits non-zero.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const TABLE = path.join(here, 'icons.json');

export function loadTable(file = TABLE) {
  const t = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (!t || typeof t.lucideStatic !== 'string' || !t.icons || typeof t.icons !== 'object') {
    throw new Error(`${file}: expected {lucideStatic, icons}`);
  }
  for (const [concept, name] of Object.entries(t.icons)) {
    if (!/^[a-z0-9-]+$/.test(concept)) throw new Error(`bad concept id: ${concept}`);
    if (typeof name !== 'string' || !/^[a-z0-9-]+$/.test(name)) throw new Error(`bad lucide name for ${concept}`);
  }
  return t;
}

// Inner markup of one lucide-static SVG file, with stroke*/fill attributes removed.
export function svgBody(src) {
  const m = /<svg\b[^>]*>([\s\S]*?)<\/svg>/.exec(src);
  if (!m) throw new Error('no <svg> element');
  return m[1]
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s(?:stroke(?:-[a-z]+)?|fill)="[^"]*"/g, '')
    .split('\n').map((l) => l.trim()).filter(Boolean).join('');
}

export function buildSprite(iconsDir, table = loadTable()) {
  const missing = [];
  const symbols = [];
  for (const [concept, name] of Object.entries(table.icons)) {
    const file = path.join(iconsDir, `${name}.svg`);
    let src;
    try { src = fs.readFileSync(file, 'utf8'); } catch { missing.push(`${concept} -> ${name}`); continue; }
    symbols.push(`<symbol id="i-${concept}" viewBox="0 0 24 24">${svgBody(src)}</symbol>`);
  }
  if (missing.length) {
    const err = new Error(`missing lucide icons in ${iconsDir}: ${missing.join(', ')}`);
    err.missing = missing;
    throw err;
  }
  return `<!-- Lucide icons (lucide-static v${table.lucideStatic}, ISC, see LICENSE). Generated by scripts/build-sprite.mjs from scripts/icons.json; do not edit. -->\n`
    + `<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('\n')}\n</svg>\n`;
}

export function buildLicense(iconsDir, table = loadTable()) {
  const text = fs.readFileSync(path.join(iconsDir, '..', 'LICENSE'), 'utf8');
  return `Lucide icons, vendored from lucide-static v${table.lucideStatic} (https://lucide.dev)\n`
    + `as public/vendor/lucide/sprite.svg by scripts/build-sprite.mjs.\n\n${text.trimEnd()}\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const dir = args[0];
  if (!dir) {
    process.stderr.write('usage: node scripts/build-sprite.mjs <lucide-static>/icons [--license <out>]\n');
    process.exit(2);
  }
  try {
    const li = args.indexOf('--license');
    if (li !== -1) {
      if (!args[li + 1]) throw new Error('--license needs an output path');
      fs.writeFileSync(args[li + 1], buildLicense(dir));
    } else {
      process.stdout.write(buildSprite(dir));
    }
  } catch (e) {
    process.stderr.write(`build-sprite: ${e.message}\n`);
    process.exit(1);
  }
}
